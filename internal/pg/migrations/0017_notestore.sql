-- Notebook content as Git's data model: every revision is the exact Git commit
-- object FMN or an import wrote, with its trees and the paths it changed, and
-- file contents are kept once per org by Git blob ID. Object IDs are the raw
-- 20-byte SHA-1 (block and segment keys the raw 32-byte SHA-256).

-- The head of each notebook. Every write locks this row first, so one
-- notebook has one writer at a time across every gateway. incarnation grows
-- each time a notebook ID is created, so a gateway can tell a notebook
-- deleted and created again from an older revision of the same one.
CREATE TABLE notebook_heads (
    org text NOT NULL,
    notebook text COLLATE "C" NOT NULL,
    seq bigint NOT NULL CHECK (seq > 0),
    commit_sha bytea NOT NULL CHECK (length(commit_sha) = 20),
    incarnation bigint GENERATED BY DEFAULT AS IDENTITY,
    PRIMARY KEY (org, notebook)
);

-- Revisions in the order they were written or imported, from 1. commit_body
-- is the commit object byte for byte; the other columns are its fields and
-- trailers for querying. parent_seq is the first parent's revision.
CREATE TABLE revisions (
    org text NOT NULL,
    notebook text COLLATE "C" NOT NULL,
    seq bigint NOT NULL CHECK (seq > 0),
    commit_sha bytea NOT NULL CHECK (length(commit_sha) = 20),
    parent_seq bigint,
    tree_sha bytea NOT NULL CHECK (length(tree_sha) = 20),
    commit_body bytea NOT NULL,
    committed_at timestamptz NOT NULL,
    author_name text NOT NULL,
    author_email text NOT NULL,
    actor text,
    source text,
    client text,
    operation_id text,
    request_id text,
    PRIMARY KEY (org, notebook, seq),
    UNIQUE (org, notebook, commit_sha)
);
-- Branch points: roots, and revisions whose first parent is not the revision
-- before them, as imported branches have. A historical read follows the
-- first-parent line through them; a notebook FMN wrote has one.
CREATE INDEX revisions_branch_points ON revisions (org, notebook, seq) WHERE parent_seq IS DISTINCT FROM seq - 1;

-- Tree objects byte for byte, shared by every revision that contains them.
CREATE TABLE git_trees (
    org text NOT NULL,
    notebook text COLLATE "C" NOT NULL,
    tree_sha bytea NOT NULL CHECK (length(tree_sha) = 20),
    body bytea NOT NULL,
    PRIMARY KEY (org, notebook, tree_sha)
);

-- File contents by Git blob ID. A file under 8 KiB is inline. A larger one is
-- split into blocks kept in the blob store under blocks/<sha256 hex>, whose
-- list is cut into content-defined segments so a small edit stores one new
-- segment instead of the whole list: segments holds, per segment, its SHA-256
-- (32 bytes) and the byte length of its blocks (8 bytes, big-endian).
CREATE TABLE file_versions (
    org text NOT NULL,
    blob_sha bytea NOT NULL CHECK (length(blob_sha) = 20),
    size bigint NOT NULL CHECK (size >= 0),
    inline bytea,
    segments bytea,
    PRIMARY KEY (org, blob_sha),
    CHECK ((inline IS NULL) <> (segments IS NULL))
);

-- Runs of a large file's block list: per block its SHA-256 (32 bytes) and size
-- (4 bytes, big-endian). touched is when a write last began to reference the
-- segment, which keeps the sweep away from writes in progress.
CREATE TABLE content_segments (
    org text NOT NULL,
    segment_sha bytea NOT NULL CHECK (length(segment_sha) = 32),
    blocks bytea NOT NULL,
    touched timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (org, segment_sha)
);

-- Every block a write put into the blob store, so the sweep finds unused ones
-- without listing the store. A write records a block here before putting it.
CREATE TABLE content_blocks (
    org text NOT NULL,
    block_sha bytea NOT NULL CHECK (length(block_sha) = 32),
    size integer NOT NULL CHECK (size >= 0),
    touched timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (org, block_sha)
);
CREATE INDEX content_blocks_touched ON content_blocks (org, touched);

-- The paths each revision changed against its first parent. entry_id is the
-- file's stable identity (a note's fmn-id), which a rename keeps, so a note's
-- history is one index range. A delete has no blob.
CREATE TABLE revision_changes (
    org text NOT NULL,
    notebook text COLLATE "C" NOT NULL,
    seq bigint NOT NULL,
    entry_id text COLLATE "C" NOT NULL,
    op text NOT NULL CHECK (op IN ('add', 'modify', 'delete', 'rename')),
    path text COLLATE "C" NOT NULL,
    old_path text COLLATE "C",
    blob_sha bytea CHECK (length(blob_sha) = 20),
    mode integer NOT NULL,
    size bigint NOT NULL DEFAULT 0,
    live_version bytea,
    PRIMARY KEY (org, notebook, seq, entry_id),
    FOREIGN KEY (org, notebook, seq) REFERENCES revisions ON DELETE CASCADE
);
CREATE INDEX revision_changes_entry ON revision_changes (org, notebook, entry_id, seq DESC);
CREATE INDEX revision_changes_path ON revision_changes (org, notebook, path, seq DESC);
CREATE INDEX revision_changes_blob ON revision_changes (org, blob_sha);

-- Each file at the head: its path, content, and Version, the commit that last
-- changed it. kind is note, asset, comments or system.
CREATE TABLE entries (
    org text NOT NULL,
    notebook text COLLATE "C" NOT NULL,
    entry_id text COLLATE "C" NOT NULL,
    path text COLLATE "C" NOT NULL,
    blob_sha bytea NOT NULL CHECK (length(blob_sha) = 20),
    mode integer NOT NULL,
    size bigint NOT NULL,
    version bytea NOT NULL CHECK (length(version) = 20),
    kind text NOT NULL,
    PRIMARY KEY (org, notebook, entry_id),
    UNIQUE (org, notebook, path)
);

-- A note's live document: the engine's snapshot (Yjs or Loro bytes) covering
-- updates through snapshot_seq, the revision it was based on, and its epoch,
-- which a purge or delete advances to drop every update and snapshot.
CREATE TABLE live_docs (
    org text NOT NULL,
    notebook text COLLATE "C" NOT NULL,
    entry_id text COLLATE "C" NOT NULL,
    epoch bigint NOT NULL CHECK (epoch >= 0),
    last_seq bigint NOT NULL DEFAULT 0 CHECK (last_seq >= 0),
    snapshot bytea,
    snapshot_seq bigint NOT NULL DEFAULT 0,
    base_version bytea CHECK (length(base_version) = 20),
    updated timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (org, notebook, entry_id)
);
CREATE TABLE live_updates (
    org text NOT NULL,
    notebook text COLLATE "C" NOT NULL,
    entry_id text COLLATE "C" NOT NULL,
    seq bigint NOT NULL CHECK (seq > 0),
    epoch bigint NOT NULL,
    actor text NOT NULL,
    body bytea NOT NULL,
    created timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (org, notebook, entry_id, seq),
    FOREIGN KEY (org, notebook, entry_id) REFERENCES live_docs ON DELETE CASCADE
);

-- Results of operations a client may retry, bound to the request they
-- answered, kept until 30 days after they finished.
CREATE TABLE operation_receipts (
    org text NOT NULL,
    notebook text COLLATE "C" NOT NULL,
    kind text COLLATE "C" NOT NULL,
    operation_id text COLLATE "C" NOT NULL,
    request_hash text NOT NULL,
    state text NOT NULL,
    result bytea,
    created timestamptz NOT NULL DEFAULT now(),
    done timestamptz,
    PRIMARY KEY (org, notebook, kind, operation_id)
);
CREATE INDEX operation_receipts_done ON operation_receipts (org, done) WHERE done IS NOT NULL;

-- A purge's rewrite of history: each old commit and the commit that replaced
-- it, so references to old SHAs keep resolving.
CREATE TABLE revision_rewrites (
    org text NOT NULL,
    notebook text COLLATE "C" NOT NULL,
    old_sha bytea NOT NULL CHECK (length(old_sha) = 20),
    new_sha bytea CHECK (length(new_sha) = 20),
    purge_id text COLLATE "C" NOT NULL,
    PRIMARY KEY (org, notebook, old_sha)
);

-- Each purge: who ran it, when and why, and what it covered. Nothing derived
-- from the purged content is kept here.
CREATE TABLE purges (
    org text NOT NULL,
    notebook text COLLATE "C" NOT NULL,
    purge_id text COLLATE "C" NOT NULL,
    actor text NOT NULL,
    reason text NOT NULL,
    scope jsonb NOT NULL,
    from_seq bigint NOT NULL,
    created timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (org, notebook, purge_id)
);

-- A retried operation finds the revision it already made by the
-- Gitnotes-Operation trailer recorded in operation_id.
CREATE INDEX revisions_operation ON revisions (org, notebook, operation_id, seq DESC) WHERE operation_id IS NOT NULL;

-- Renames away from a path, so its last version and folder history need no
-- scan of the notebook's changes.
CREATE INDEX revision_changes_old_path ON revision_changes (org, notebook, old_path, seq DESC) WHERE old_path IS NOT NULL;
